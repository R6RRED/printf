void	ft_putnbr_fd(int n)
{
	long	nb;

	nb = n;
	if (nb < 0)
	{
		ft_putchar_fd('-', 1);
		nb = -nb;
	}
	if (nb >= 10)
		ft_putnbr_fd(nb / 10);
	ft_putchar_fd((nb % 10) + '0', 1);
}
